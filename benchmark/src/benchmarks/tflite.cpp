tflite::MicroMutableOpResolver<64> g_tflite_resolver;
static tflite::MicroInterpreter *gp_interpreter_;

static const size_t g_tflite_buffer_size = 20;

static uint8_t __attribute__((aligned(32))) g_tflite_buffer[g_tflite_buffer_size * 1024];
static size_t buffer_pos = 0;

static void model_init(void)
{
	g_tflite_resolver.AddConv2D();
	g_tflite_resolver.AddFullyConnected();
	g_tflite_resolver.AddMaxPool2D();
	g_tflite_resolver.AddReshape();
	g_tflite_resolver.AddSoftmax();
}

static int model_load(const uint8_t *model, tflite::MicroInterpreter*& gp_interpreter = gp_interpreter_, size_t tensor_arena_size = 0)
{
	if (gp_interpreter != nullptr) {
		printk("GP interpreter is already initialized\n");
		return 1;
	}
	uint8_t *tensor_arena = g_tflite_buffer + buffer_pos;
	if (tensor_arena_size == 0) {
		tensor_arena_size = g_tflite_buffer_size * 1024 - buffer_pos;
	}

	if (buffer_pos + tensor_arena_size > g_tflite_buffer_size * 1024) {
		printk("Not enough space in buffer\n");
		return 1;
	}

	const tflite::Model *tflite_model = tflite::GetModel(model);
	if (tflite_model->version() != TFLITE_SCHEMA_VERSION) {
		return 1;
	}

	gp_interpreter = new tflite::MicroInterpreter(
	    tflite_model, g_tflite_resolver, tensor_arena, tensor_arena_size);

	TfLiteStatus allocate_status = gp_interpreter->AllocateTensors();
	if (allocate_status != kTfLiteOk) {
		delete gp_interpreter;
		return 1;
	}

	buffer_pos += tensor_arena_size;
	return 0;
}

static int model_load_input(tflite::MicroInterpreter * const gp_interpreter, const uint8_t *input, uint32_t input_size)
{
	if (gp_interpreter == nullptr) {
		printk("Provided uninitialized interpreter\n");
		return 1;
	}
	TfLiteTensor *model_input = gp_interpreter->input(0);
	if (model_input->bytes != input_size) {
		printk("%d != %d\n", model_input->bytes, input_size);
		return 1;
	}
	memcpy(model_input->data.data, input, model_input->bytes);
	return 0;
}

static int model_load_input(const uint8_t *input, uint32_t input_size) {
	return model_load_input(gp_interpreter_, input, input_size);
}

static int model_run(tflite::MicroInterpreter * const gp_interpreter)
{
	if (gp_interpreter == nullptr) {
		printk("Provided uninitialized interpreter\n");
		return 1;
	}
	TfLiteStatus status = gp_interpreter->Invoke();
	if (status != kTfLiteOk) {
		return 1;
	}

	return 0;
}

static int model_run() {
	return model_run(gp_interpreter_);
}

static int model_get_output(tflite::MicroInterpreter * const gp_interpreter, uint8_t *output, uint32_t output_size)
{
	if (gp_interpreter == nullptr) {
		printk("Provided uninitialized interpreter\n");
		return 1;
	}
	TfLiteTensor *model_output = gp_interpreter->output(0);
	if (model_output->bytes != output_size) {
		return 1;
	}
	memcpy(output, model_output->data.data, model_output->bytes);
	return 0;
}

static int model_get_output(uint8_t *output, uint32_t output_size) {
	return model_get_output(gp_interpreter_, output, output_size);
}


#define N_SAMPLES     10
#define INPUT_MIN_VAL 0.0f
#define INPUT_MAX_VAL (2.0f * 3.14159265359f)

#define INPUT_SCALE 0.024573976173996925f
#define INPUT_ZERO  -128

#define OUTPUT_SCALE 0.008472034707665443f
#define OUTPUT_ZERO  4

ZPL_CODE_SCOPE_DEFINE(prepare_model, true);

void loop();

void rand_input(float *model_input);

void loop()
{
	int status = 0;
	float model_input;
	uint8_t model_input_q;
	float model_output;
	uint8_t model_output_q;

	rand_input(&model_input);
	model_input_q = (model_input / INPUT_SCALE) + INPUT_ZERO;

	status = model_load_input((uint8_t *)&model_input_q, sizeof(uint8_t));
	if (status) {
		printk("Model load input failed %d\n", status);
		return;
	}

	status = model_run();
	if (status) {
		printk("Model run failed %d\n", status);
		return;
	}

	status = model_get_output((uint8_t *)&model_output_q, sizeof(uint8_t));
	if (status) {
		printk("Model get output failed %d\n", status);
		return;
	}
	model_output = (model_output_q - OUTPUT_ZERO) * OUTPUT_SCALE;

	printk("x_value: %f, y_value: %f\n", (double)model_input, (double)model_output);
}

void rand_input(float *model_input)
{
	*model_input =
		((INPUT_MAX_VAL - INPUT_MIN_VAL) * (float)sys_rand32_get() / (float)0xFFFFFFFF) +
		INPUT_MIN_VAL;
}


